mod common;

use std::time::Duration;

use common::*;
use omni_chat::chat::PostOutcome;
use tokio::time::Instant;

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn leader_failover_keeps_context() {
    let c = cluster(Duration::ZERO).await;
    let old = c.wait_for_leader(T).await.unwrap();
    let survivors = others(old);

    chat(&c, old, "my name is Ada").await;
    chat(&c, survivors[0], "remember that").await;
    let before = converged(&c, &[1, 2, 3], 4).await;

    c.crash(old);
    let new = leader_among(&c, &survivors).await;
    assert_ne!(new, old);

    // History survived on the survivors...
    assert_eq!(converged(&c, &survivors, 4).await, before);
    // ...and the next reply is generated by the new leader with full context.
    let (_, reply) = chat(&c, survivors[1], "what is my name?").await;
    // Leadership can still move between the survivors; it just can't be the dead node.
    assert!(survivors.contains(&reply.node), "{reply:?}");
    assert!(reply.content.contains("turn 3"), "{}", reply.content);
    assert!(
        reply.content.contains("my name is Ada"),
        "{}",
        reply.content
    );

    let after = converged(&c, &survivors, 6).await;
    assert_eq!(after[..4], before[..]);
    assert_one_reply_each(&after);
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn crash_mid_generation_is_answered_by_new_leader() {
    let c = cluster(Duration::from_millis(400)).await;
    let old = c.wait_for_leader(T).await.unwrap();
    let survivors = others(old);
    let via = c.node(survivors[0]).shared.clone();

    // User message gets decided; leader starts a slow reply; leader dies.
    let post = tokio::spawn(async move { via.post("slow one".into(), None, T).await.unwrap() });
    let s = c.node(survivors[0]).shared.clone();
    assert!(
        s.wait_until(|t| t.turns().len() == 1, Instant::now() + T)
            .await
    );
    tokio::time::sleep(Duration::from_millis(100)).await;
    c.crash(old);

    leader_among(&c, &survivors).await;
    match post.await.unwrap() {
        PostOutcome::Replied { reply, .. } => assert_ne!(reply.node, old),
        o => panic!("{o:?}"),
    }
    let msgs = converged(&c, &survivors, 2).await;
    assert_one_reply_each(&msgs);
}

/// The old leader is cut off but alive, so it keeps generating. Its reply must
/// not end up as a second answer after the partition heals.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn partitioned_old_leader_causes_no_duplicate_reply() {
    let c = cluster(Duration::from_millis(300)).await;
    let old = c.wait_for_leader(T).await.unwrap();
    let survivors = others(old);
    let via = c.node(survivors[0]).shared.clone();

    let post = tokio::spawn(async move { via.post("contested".into(), None, T).await.unwrap() });
    let s = c.node(survivors[0]).shared.clone();
    assert!(
        s.wait_until(|t| t.turns().len() == 1, Instant::now() + T)
            .await
    );
    tokio::time::sleep(Duration::from_millis(50)).await;
    c.net.partition(old);

    leader_among(&c, &survivors).await;
    assert!(matches!(post.await.unwrap(), PostOutcome::Replied { .. }));
    chat(&c, survivors[1], "after the split").await;

    // Let the zombie finish its inference and try to propose, then heal.
    tokio::time::sleep(Duration::from_millis(500)).await;
    c.net.heal(old).await;

    let msgs = converged(&c, &[1, 2, 3], 4).await;
    assert_one_reply_each(&msgs);
    // Leadership may move between the survivors again, but the cut-off
    // zombie's reply must never win.
    assert!(msgs
        .iter()
        .filter(|m| m.in_reply_to.is_some())
        .all(|m| m.node != old));
}
