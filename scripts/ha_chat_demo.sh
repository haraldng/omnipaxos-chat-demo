#!/usr/bin/env bash
# HA chat demo: 3 replicas as separate OS processes, kill -9 the leader,
# continue the same conversation on a survivor.
#
#   scripts/ha_chat_demo.sh                 # mock model, no GPU/network
#   MODEL=ollama scripts/ha_chat_demo.sh    # local Ollama (llama3.1:8b by default)
set -euo pipefail

cd "$(dirname "$0")/.."
MODEL=${MODEL:-mock}
MODEL_NAME=${MODEL_NAME:-llama3.1:8b}
BASE_PORT=${BASE_PORT:-8080}
NODES=3
LOG_DIR=${LOG_DIR:-target/demo-logs}
BIN=target/debug/omni_chat

bold() { printf '\n\033[1m== %s\033[0m\n' "$*"; }
url() { echo "http://127.0.0.1:$((BASE_PORT + $1))"; }
json() { if command -v jq >/dev/null; then jq "$@"; else python3 -m json.tool; fi; }

leader_of() { # node -> leader id as that node sees it (empty if none/unreachable)
  curl -sf "$(url "$1")/admin/status" | python3 -c 'import sys,json; d=json.load(sys.stdin); print(d["leader"] if d["is_leader"] or d["accepted"] else "")' 2>/dev/null || true
}

wait_leader() { # node... -> prints the leader all of them agree on
  for _ in $(seq 1 100); do
    local first="" agree=1
    for n in "$@"; do
      local l; l=$(leader_of "$n")
      [[ -z "$l" ]] && { agree=0; break; }
      [[ -z "$first" ]] && first=$l
      [[ "$l" != "$first" ]] && { agree=0; break; }
    done
    if [[ $agree == 1 && -n "$first" && " $* " == *" $first "* ]]; then echo "$first"; return; fi
    sleep 0.1
  done
  echo "no leader among $*" >&2; exit 1
}

say() { # node text
  printf '\n\033[36muser@node%s>\033[0m %s\n' "$1" "$2"
  curl -sf -X POST "$(url "$1")/v1/chat" -H 'content-type: application/json' \
    -d "$(python3 -c 'import json,sys; print(json.dumps({"content": sys.argv[1]}))' "$2")" |
    python3 -c 'import sys,json; d=json.load(sys.stdin); r=d.get("reply"); print("\033[33massistant (generated by node %s)>\033[0m %s" % (r["node"], r["content"]) if r else "pending: %s" % d)'
}

transcript() {
  curl -sf "$(url "$1")/v1/chat" | python3 -c '
import sys, json
d = json.load(sys.stdin)
print("node %s | leader %s | decided_len %s" % (d["node_id"], d["leader"], d["decided_len"]))
for m in d["messages"]:
    print("  [%2d] %-9s %s" % (m["log_idx"], m["role"], m["content"]))'
}

cargo build -q
mkdir -p "$LOG_DIR"
DATA_DIR=${DATA_DIR:-target/omni-chat-data}
rm -rf "$DATA_DIR"
declare -a PIDS
cleanup() { kill "${PIDS[@]}" 2>/dev/null || true; }
trap cleanup EXIT

bold "Starting $NODES replicas (model=$MODEL); logs in $LOG_DIR/"
for id in $(seq 1 $NODES); do
  RUST_LOG=${RUST_LOG:-info} "$BIN" node --id "$id" --nodes $NODES --base-port "$BASE_PORT" \
    --model "$MODEL" --model-name "$MODEL_NAME" --data-dir "$DATA_DIR" \
    >"$LOG_DIR/node$id.log" 2>&1 &
  PIDS[$id]=$!
  echo "node $id: pid ${PIDS[$id]}, $(url "$id")"
done

LEADER=$(wait_leader 1 2 3)
bold "Leader is node $LEADER"

bold "Chatting via node 1"
say 1 "Hi! My name is Ada and I love distributed systems."
say 1 "What's a good first project?"
say 1 "Remember my name, I'll ask later."

bold "Transcript on node 1"
transcript 1

bold "Status"
for id in 1 2 3; do curl -sf "$(url "$id")/admin/status" | json -c . 2>/dev/null || curl -sf "$(url "$id")/admin/status"; echo; done

# Leadership can move while the nodes start up; kill whoever leads now.
LEADER=$(wait_leader 1 2 3)
bold "kill -9 leader (node $LEADER, pid ${PIDS[$LEADER]})"
{ kill -9 "${PIDS[$LEADER]}"; wait "${PIDS[$LEADER]}"; } 2>/dev/null || true
SURVIVORS=()
for id in 1 2 3; do [[ $id != "$LEADER" ]] && SURVIVORS+=("$id"); done

NEW=$(wait_leader "${SURVIVORS[@]}")
bold "New leader is node $NEW (survivors: ${SURVIVORS[*]})"

OTHER=${SURVIVORS[0]}; [[ $OTHER == "$NEW" ]] && OTHER=${SURVIVORS[1]}
bold "Transcript on surviving node $OTHER — history intact"
transcript "$OTHER"

bold "Continue the same chat via node $OTHER"
say "$OTHER" "Do you still remember my name?"

bold "Final transcript on node $NEW"
transcript "$NEW"
